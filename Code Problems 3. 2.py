number1 = int(input("What is your first number?"))
number2 = int(input("What is your second number?"))

if number1 == number2:
    print("Your first number,", number1, "is equal to your second number,", number2)
if number1 > number2:
    print("Your first number,", number1, "is greater than your second number,", number2)
if number1 < number2:
    print("Your first number,", number1, "is lesser than your second number,", number2)
