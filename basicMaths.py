num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))

#Addition
print(str(num1) + " + "  + str(num2) + " = " + str(num1 + num2))

#Subtraction
print(str(num1) + " - " + str(num2) + " = " + str(num1 - num2))

#Multiplication
print(str(num1) + " * " + str(num2) + " = " + str(num1 * num2))

#Division
print(str(num1) + " / " + str(num2) + " = " + str(num1 / num2))

#Quotient
print(str(num1) + " DIV " + str(num2) + " = " + str(num1 // num2))

#Modulus
print(str(num1) + " MOD " + str(num2) + " = " + str(num1 % num2))

#Exponentiation
print(str(num1) + " ^ " + str(num2) + " = " + str(num1 ** num2))
